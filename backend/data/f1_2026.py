def get_circuit_pit_loss(circuit_name_or_id: str, track_status: str = "1") -> float:
    """
    Retourne la perte de temps estimée aux stands (en secondes)
    selon le circuit et l'éventuelle neutralisation de course (VSC / SC).
    """
    spec = None
    c_lower = (circuit_name_or_id or "").lower()
    for cid, s in CIRCUIT_SPECS.items():
        if cid in c_lower or c_lower in cid:
            spec = s
            break

    base_loss = spec.get("pit_loss_seconds", 22.5) if spec else 22.5
    if track_status == "4":    # Safety Car (~ -55% de perte nette)
        return round(base_loss * 0.45, 1)
    elif track_status == "6":  # Virtual Safety Car (~ -35% de perte nette)
        return round(base_loss * 0.65, 1)
    return base_loss



